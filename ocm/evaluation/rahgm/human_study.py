def _condition_table(
    per_condition: dict[str, list[ParticipantResult]]
) -> dict[str, dict[str, Any]]:
    """Table 5: accuracy, time, TLX, and ECE by governance condition."""
    out: dict[str, dict[str, Any]] = {}
    for name, results in per_condition.items():
        traces = [t for r in results for t in r.traces]
        if not traces:
            out[name] = {"n_participants": 0, "n_items": 0}
            continue
        correctness = [1.0 if t.correct else 0.0 for t in traces]
        confidences = [t.confidence for t in traces]
        accuracy, low, high = cluster_bootstrap_ci(
            correctness, [t.analyst_id for t in traces], seed=17
        )
        out[name] = {
            "n_participants": len(results),
            "n_items": len(traces),
            "accuracy": accuracy,
            "accuracy_ci95": [low, high],
            "median_seconds": _median([t.seconds for t in traces]),
            "mean_seconds": sum(t.seconds for t in traces) / len(traces),
            "workload_tlx": sum(t.workload for t in traces) / len(traces),
            "ece": expected_calibration_error(confidences, correctness),
            "brier": brier_score(confidences, correctness),
            "recommendation_following_rate": sum(
                1 for t in traces if t.followed_recommendation
            )
            / len(traces),
            "mean_evidence_opened": sum(t.evidence_opened for t in traces) / len(traces),
            "mean_confidence": sum(confidences) / len(traces),
        }
    return out


def _depth_table(
    traces: Sequence[tuple[Condition, AdjudicationTrace]]
) -> dict[str, dict[str, Any]]:
    """Outcomes by explanation depth, pooled across conditions."""
    out: dict[str, dict[str, Any]] = {}
    for depth in DEPTH_ORDER:
        subset = [t for _c, t in traces if t.depth is depth]
        if not subset:
            out[depth.value] = {"n_items": 0}
            continue
        correctness = [1.0 if t.correct else 0.0 for t in subset]
        confidences = [t.confidence for t in subset]
        out[depth.value] = {
            "n_items": len(subset),
            "accuracy": sum(correctness) / len(subset),
            "median_seconds": _median([t.seconds for t in subset]),
            "workload_tlx": sum(t.workload for t in subset) / len(subset),
            "ece": expected_calibration_error(confidences, correctness),
            "brier": brier_score(confidences, correctness),
            "mean_evidence_opened": sum(t.evidence_opened for t in subset) / len(subset),
            "recommendation_following_rate": sum(
                1 for t in subset if t.followed_recommendation
            )
            / len(subset),
            "calibration_bins": [
                b.as_dict() for b in calibration_bins(confidences, correctness)
            ],
        }
    return out


def _cross_table(
    traces: Sequence[tuple[Condition, AdjudicationTrace]]
) -> dict[str, dict[str, Any]]:
    """Condition × depth accuracy and time cells."""
    out: dict[str, dict[str, Any]] = {}
    for condition in HUMAN_FACING:
        for depth in DEPTH_ORDER:
            subset = [
                t for c, t in traces if c is condition and t.depth is depth
            ]
            key = f"{condition.value}|{depth.value}"
            if not subset:
                out[key] = {"n_items": 0}
                continue
            out[key] = {
                "n_items": len(subset),
                "accuracy": sum(1 for t in subset if t.correct) / len(subset),
                "median_seconds": _median([t.seconds for t in subset]),
                "workload_tlx": sum(t.workload for t in subset) / len(subset),
            }
    return out


def _complacency(
    traces: Sequence[tuple[Condition, AdjudicationTrace]]
) -> dict[str, Any]:
    """Automation-bias analysis by trial position and recommendation streak (§4.3)."""
    if not traces:
        return {}
    flat = [t for _c, t in traces]
    scenarios = sorted({t.scenario_index for t in flat})
    first, last = scenarios[0], scenarios[-1]

    def _slice(index: int) -> tuple[float, float]:
        subset = [t for t in flat if t.scenario_index == index]
        if not subset:
            return float("nan"), float("nan")
        return (
            sum(1 for t in subset if t.followed_recommendation) / len(subset),
            sum(1 for t in subset if t.correct) / len(subset),
        )

    first_follow, first_accuracy = _slice(first)
    last_follow, last_accuracy = _slice(last)

    by_streak: dict[str, dict[str, float]] = {}
    for bucket, label in ((0, "0"), (1, "1-2"), (3, "3-5"), (6, "6+")):
        if label == "0":
            subset = [t for t in flat if t.streak_before == 0]
        elif label == "1-2":
            subset = [t for t in flat if 1 <= t.streak_before <= 2]
        elif label == "3-5":
            subset = [t for t in flat if 3 <= t.streak_before <= 5]
        else:
            subset = [t for t in flat if t.streak_before >= 6]
        if not subset:
            continue
        by_streak[label] = {
            "n": float(len(subset)),
            "recommendation_following_rate": sum(
                1 for t in subset if t.followed_recommendation
            )
            / len(subset),
            "accuracy": sum(1 for t in subset if t.correct) / len(subset),
            "median_seconds": _median([t.seconds for t in subset]),
        }

    return {
        "first_scenario": first,
        "last_scenario": last,
        "recommendation_following_change_points": 100.0 * (last_follow - first_follow),
        "accuracy_change_points": 100.0 * (last_accuracy - first_accuracy),
        "first_scenario_following": first_follow,
        "last_scenario_following": last_follow,
        "first_scenario_accuracy": first_accuracy,
        "last_scenario_accuracy": last_accuracy,
        "by_streak": by_streak,
        "note": (
            "Reliance growth is generated by the simulated analyst's automation-bias "
            "model; it characterizes the measurement, not human behavior."
        ),
    }


def _median(values: Sequence[float]) -> float:
    """Median of a sequence."""
    if not values:
        return float("nan")
    ordered = sorted(values)
    mid = len(ordered) // 2
    return ordered[mid] if len(ordered) % 2 else 0.5 * (ordered[mid - 1] + ordered[mid])


# --------------------------------------------------------------------------- #
# Models (§3.7 eq. 12)
# --------------------------------------------------------------------------- #
def _design(
    traces: Sequence[tuple[Condition, AdjudicationTrace]]
) -> tuple[list[list[float]], list[str], list[str], list[str]]:
    """Build the eq. (12) fixed-effect design matrix.

    Reference cells: ``frozen_rahgm`` for condition and ``minimal`` for depth, so
    the reported coefficients are the contrasts the paper names.
    """
    conditions = [c for c in HUMAN_FACING if c is not Condition.frozen_rahgm]
    depths = [d for d in DEPTH_ORDER if d is not ExplanationDepth.minimal]

    names = ["intercept"]
    names += [f"condition[{c.value}]" for c in conditions]
    names += [f"depth[{d.value}]" for d in depths]
    names += ["consequential", "k", "trial_position"]

    rows: list[list[float]] = []
    participants: list[str] = []
    scenarios: list[str] = []
    for condition, trace in traces:
        row = [1.0]
        row += [1.0 if condition is c else 0.0 for c in conditions]
        row += [1.0 if trace.depth is d else 0.0 for d in depths]
        row += [
            1.0 if trace.consequential else 0.0,
            float(trace.k),
            float(trace.trial_index) / 100.0,
        ]
        rows.append(row)
        participants.append(f"{condition.value}:{trace.analyst_id}")
        scenarios.append(str(trace.scenario_index))
    return rows, names, participants, scenarios


def _fit_models(
    traces: Sequence[tuple[Condition, AdjudicationTrace]]
) -> dict[str, Any]:
    """Fit the three §3.7 models."""
    rows, names, participants, scenarios = _design(traces)
    flat = [t for _c, t in traces]

    accuracy_fit = RandomInterceptLogit().fit(
        [1.0 if t.correct else 0.0 for t in flat],
        rows,
        participants,
        scenarios,
        names=names,
    )
    time_fit = RandomInterceptGaussian().fit(
        [math.log(max(t.seconds, 0.1)) for t in flat],
        rows,
        participants,
        scenarios,
        names=names,
    )
    # NASA-TLX is binned into quintiles for the cumulative-logit link.
    workloads = [t.workload for t in flat]
    ordered = sorted(workloads)
    cuts = [ordered[int(len(ordered) * q)] for q in (0.2, 0.4, 0.6, 0.8)]
    levels = [sum(1 for c in cuts if w > c) for w in workloads]
    workload_fit = CumulativeLogit().fit(
        levels,
        [row[1:] for row in rows],  # cutpoints absorb the intercept
        participants,
        names=names[1:],
    )

    return {
        "adjudication_accuracy": accuracy_fit.as_dict(),
        "log_decision_time": time_fit.as_dict(),
        "workload_tlx_ordinal": workload_fit.as_dict(),
    }


def _primary_contrasts(
    models: dict[str, Any], traces: Sequence[tuple[Condition, AdjudicationTrace]]
) -> dict[str, Any]:
    """The three preregistered contrasts with Holm correction (Req 12.3).

    C4 vs C3 tests the routing mechanism, C5 vs C4 tests feedback adaptation, and
    the depth contrast tests RQ2. Because ``frozen_rahgm`` is the reference cell,
    the C4-vs-C3 and C5-vs-C4 contrasts read directly off the accuracy model's
    condition coefficients.
    """
    coefficients = {
        c["name"]: c for c in models["adjudication_accuracy"]["coefficients"]
    }
    tests: list[tuple[str, float]] = []
    detail: dict[str, Any] = {}

    for label, name in (
        ("C4_vs_C3_routing_mechanism", f"condition[{Condition.fixed_threshold.value}]"),
        ("C5_vs_C4_feedback_adaptation", f"condition[{Condition.adaptive_rahgm.value}]"),
        ("depth_evidence_vs_minimal", f"depth[{ExplanationDepth.evidence.value}]"),
    ):
        coefficient = coefficients.get(name)
        p = float(coefficient["p_value"]) if coefficient else float("nan")
        tests.append((label, p))
        detail[label] = coefficient

    corrected = holm(tests)
    return {
        "reference_cells": {"condition": "frozen_rahgm", "depth": "minimal"},
        "coefficients": detail,
        "holm": [r.as_dict() for r in corrected],
        "note": (
            "Contrasts are computed on simulated adjudications; the depth contrast "
            "in particular restates the simulated analyst's assumed competence "
            "profile and is not human-subjects evidence."
        ),
    }
