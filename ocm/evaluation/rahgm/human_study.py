"""Experiment 2 — explanation depth and reliance (paper §3.6, §4.3, Table 5).

**Simulated, not human.** Paper §3.6 preregisters 80 participants with analytic
experience, assigned in equal groups of 20 to the four human-facing conditions,
each completing eight scenarios of 20 candidate writes with counterbalanced
scenario order and explanation depth. No human participants are available here, so
this module runs that exact protocol against the
:class:`~ocm.evaluation.rahgm.analyst.SimulatedAnalyst`.

What this delivers: the full §3.6 measurement apparatus — per-item decision, time,
evidence opened, action changes, confidence, recommendation-following, NASA-TLX,
and the calibration measures of eq. (11) — plus the §3.7 mixed-effects analysis
with Holm-corrected primary contrasts, all exercised end to end on data with the
right shape and dependence structure.

What this does **not** deliver: an answer to RQ2. Any explanation-depth effect
reported here is a consequence of :data:`~ocm.evaluation.rahgm.analyst.DEPTH_COMPETENCE`,
which is an assumption about people, not a measurement of them. Every emitted
artifact carries that disclosure.

Requirements: 6.3, 11.3, 12.1, 12.2, 12.3, 13.3, 14.1, 14.2.
"""

