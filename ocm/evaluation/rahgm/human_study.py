#: §3.6 protocol constants.
PARTICIPANTS_PER_CONDITION = 20
SCENARIOS_PER_PARTICIPANT = 8
WRITES_PER_SCENARIO = 20

#: Mapping from a gold transition to the review action that realizes it.
_GOLD_ACTION: dict[Tier, ReviewAction] = {
    Tier.accept: ReviewAction.accept,
    Tier.supersede: ReviewAction.supersede,
    Tier.reject: ReviewAction.reject,
    Tier.review: ReviewAction.quarantine,
}


@dataclass
class ParticipantResult:
    """One simulated participant's session."""

    analyst_id: str
    condition: Condition
    traces: list[AdjudicationTrace]

    @property
    def accuracy(self) -> float:
        """Adjudication accuracy."""
        return (
            sum(1 for t in self.traces if t.correct) / len(self.traces)
            if self.traces
            else float("nan")
        )

    @property
    def median_seconds(self) -> float:
        """Median decision time."""
        if not self.traces:
            return float("nan")
        values = sorted(t.seconds for t in self.traces)
        mid = len(values) // 2
        return (
            values[mid]
            if len(values) % 2
            else 0.5 * (values[mid - 1] + values[mid])
        )

    @property
    def mean_workload(self) -> float:
        """Mean NASA-TLX workload."""
        return (
            sum(t.workload for t in self.traces) / len(self.traces)
            if self.traces
            else float("nan")
        )


def _queue_items(
    corpus: RahgmCorpus,
    condition: Condition,
    developed: DevelopedPolicy,
    *,
    partition: Partition = Partition.test,
) -> list[tuple[ReviewItem, ReviewAction, int]]:
    """Produce the review queue a condition generates, with each item's gold action.

    The queue is generated by a real replay under the condition's own router, so
    each condition presents exactly the items its routing policy escalates — which
    is what makes the condition contrast meaningful rather than a re-labelling of
    one fixed queue.
    """
    scenarios = corpus.partition(partition)
    writes_by_id = {w.write_id: w for s in scenarios for w in s.writes}
    replayer = ScenarioReplayer(
        condition,
        params=developed.params,
        reviewer=make_oracle_reviewer(writes_by_id),
        collect_cases=False,
    )
    results, _harness = replayer.run_corpus(scenarios)

    out: list[tuple[ReviewItem, ReviewAction, int]] = []
    for scenario_index, result in enumerate(results):
        for item in result.review_items:
            write = writes_by_id.get(item.write_id or "")
            if write is None:
                continue
            item.consequential = write.consequential
            out.append((item, _GOLD_ACTION[write.gold_transition], scenario_index))
    return out


def run_experiment2(
    corpus: RahgmCorpus | None = None,
    *,
    developed: DevelopedPolicy | None = None,
    participants_per_condition: int = PARTICIPANTS_PER_CONDITION,
    scenarios_per_participant: int = SCENARIOS_PER_PARTICIPANT,
    writes_per_scenario: int = WRITES_PER_SCENARIO,
    seed: int = 1337,
    fit_models: bool = True,
) -> dict[str, Any]:
    """Run the simulated explanation-depth and reliance study (Table 5).

    Args:
        corpus: The evaluation corpus.
        developed: The fitted policy.
        participants_per_condition: 20 in the paper.
        scenarios_per_participant: 8 in the paper.
        writes_per_scenario: 20 in the paper.
        seed: Base seed for participant sampling.
        fit_models: Whether to fit the §3.7 mixed-effects models.

    Returns:
        A report dict with per-condition and per-depth outcomes, calibration, the
        complacency analysis, the fitted models, Holm-corrected contrasts, and the
        simulation disclosure.
    """
    corpus = corpus or generate_corpus()
    developed = developed or develop_policy(corpus)

    per_condition: dict[str, list[ParticipantResult]] = {}
    all_traces: list[tuple[Condition, AdjudicationTrace]] = []

    for condition_index, condition in enumerate(HUMAN_FACING):
        items = _queue_items(corpus, condition, developed)
        results: list[ParticipantResult] = []

        if not items:
            per_condition[condition.value] = results
            continue

        profiles = sample_profiles(
            participants_per_condition, seed=seed + 1000 * condition_index
        )
        for participant_index, profile in enumerate(profiles):
            analyst = SimulatedAnalyst(profile)
            # Counterbalancing: scenario order rotates by participant and the
            # depth schedule is a Latin square offset by participant (Req 6.3).
            depths = depth_schedule(
                scenarios_per_participant, offset=participant_index % len(DEPTH_ORDER)
            )
            traces: list[AdjudicationTrace] = []
            for scenario_slot in range(scenarios_per_participant):
                depth = depths[scenario_slot]
                start = (
                    (participant_index * scenarios_per_participant + scenario_slot)
                    * writes_per_scenario
                ) % len(items)
                block = [
                    items[(start + offset) % len(items)]
                    for offset in range(min(writes_per_scenario, len(items)))
                ]
                for item, gold_action, _origin in block:
                    traces.append(
                        analyst.adjudicate(
                            item,
                            depth,
                            gold_action,
                            scenario_index=scenario_slot,
                        )
                    )
            result = ParticipantResult(
                analyst_id=profile.analyst_id,
                condition=condition,
                traces=traces,
            )
            results.append(result)
            all_traces.extend((condition, t) for t in traces)

        per_condition[condition.value] = results

    report: dict[str, Any] = {
        "experiment": "experiment2_explanation_depth_and_reliance",
        "simulated": True,
        "disclosure": SIMULATION_DISCLOSURE,
        "protocol": {
            "participants_per_condition": participants_per_condition,
            "scenarios_per_participant": scenarios_per_participant,
            "writes_per_scenario": writes_per_scenario,
            "conditions": [c.value for c in HUMAN_FACING],
            "explanation_depths": [d.value for d in DEPTH_ORDER],
            "counterbalancing": "Latin-square depth schedule, participant-rotated scenario order",
        },
        "by_condition": _condition_table(per_condition),
        "by_depth": _depth_table(all_traces),
        "by_condition_and_depth": _cross_table(all_traces),
        "complacency": _complacency(all_traces),
        "n_adjudications": len(all_traces),
    }

    if fit_models and all_traces:
        report["models"] = _fit_models(all_traces)
        report["primary_contrasts"] = _primary_contrasts(report["models"], all_traces)

    return report


